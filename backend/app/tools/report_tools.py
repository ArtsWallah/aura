import uuid
from html import escape
from typing import Any
from urllib.parse import quote
from pydantic import BaseModel, Field

from app.tools.schemas import ToolCategory, ExecutionLocation, PermissionLevel
from app.tools.registry import tool_registry
from app.core.config import settings
from app.privacy.encryption import encryption_service

class GenerateReportInput(BaseModel):
    title: str = Field(description="Title of the report.")
    executive_summary: str = Field(description="High-level overview and direct answers to user objective.")
    findings: list[str] = Field(description="List of key analytical findings backed by data.")
    recommendations: list[str] = Field(default_factory=list, description="Actionable recommendations.")
    chart_paths: list[str] = Field(default_factory=list, description="List of chart image paths generated by visualization tools.")
    tables: list[dict[str, Any]] = Field(default_factory=list, description="Data tables or metric dictionaries.")
    assumptions_and_limitations: list[str] = Field(
        default=["Analysis based strictly on provided dataset.", "Outliers and missing values handled as documented."],
        description="Explicit limitations and assumptions."
    )
    task_id: str | None = Field(default=None, exclude=True)

@tool_registry.register(
    name="generate_report",
    category=ToolCategory.REPORT,
    description="Synthesizes analytical results, embedded visualizations, and strategic recommendations into publication-grade Markdown and HTML reports.",
    input_model=GenerateReportInput,
    execution_location=ExecutionLocation.LOCAL,
    permission_level=PermissionLevel.EXECUTE
)
def generate_report(params: GenerateReportInput) -> dict[str, Any]:
    report_id = f"report_{uuid.uuid4().hex[:10]}"
    
    # 1. Build Markdown content
    md_lines = [
        f"# {params.title}",
        "",
        "## Executive Summary",
        params.executive_summary,
        "",
        "## Key Analytical Findings"
    ]
    
    for f in params.findings:
        md_lines.append(f"- {f}")
        
    chart_urls = [
        f"/api/tasks/{quote(params.task_id, safe='')}/artifacts/chart/{index}"
        for index, _ in enumerate(params.chart_paths)
    ] if params.task_id else []

    if chart_urls:
        md_lines.append("")
        md_lines.append("## Visual Insights")
        for chart_url in chart_urls:
            md_lines.append(f"![Visual Chart]({chart_url})")
            md_lines.append("")

    if params.recommendations:
        md_lines.append("## Actionable Recommendations")
        for r in params.recommendations:
            md_lines.append(f"1. {r}")
        md_lines.append("")

    md_lines.append("## Assumptions & Limitations")
    for lim in params.assumptions_and_limitations:
        md_lines.append(f"- *{lim}*")
        
    markdown_content = "\n".join(md_lines)
    
    # 2. Build polished HTML version
    html_charts = ""
    for chart_url in chart_urls:
        safe_chart_url = escape(chart_url, quote=True)
        html_charts += f"""
        <div style="margin: 20px 0; text-align: center;">
            <img src="{safe_chart_url}" style="max-width: 100%; border-radius: 8px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1);" alt="Chart" />
        </div>
        """

    html_findings = "".join([f"<li style='margin-bottom: 8px;'>{escape(f)}</li>" for f in params.findings])
    html_recommendations = "".join([f"<li style='margin-bottom: 8px;'><strong>{escape(r)}</strong></li>" for r in params.recommendations])
    html_limitations = "".join([f"<li><em>{escape(lim)}</em></li>" for lim in params.assumptions_and_limitations])

    html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{escape(params.title)}</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; line-height: 1.6; color: #1e293b; max-width: 860px; margin: 40px auto; padding: 0 20px; }}
        h1 {{ color: #0f172a; border-bottom: 2px solid #e2e8f0; padding-bottom: 12px; }}
        h2 {{ color: #1e40af; margin-top: 30px; }}
        .badge {{ background: #eff6ff; color: #1d4ed8; padding: 4px 10px; border-radius: 12px; font-size: 12px; font-weight: bold; display: inline-block; }}
        .card {{ background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 18px; margin: 15px 0; }}
    </style>
</head>
<body>
    <span class="badge">AURA Autonomous Analytics</span>
    <h1>{escape(params.title)}</h1>
    
    <div class="card">
        <h3>Executive Summary</h3>
        <p>{escape(params.executive_summary)}</p>
    </div>

    <h2>Key Findings</h2>
    <ul>{html_findings}</ul>

    {f"<h2>Visualizations</h2>{html_charts}" if html_charts else ""}

    {f"<h2>Actionable Recommendations</h2><ol>{html_recommendations}</ol>" if html_recommendations else ""}

    <h2>Assumptions & Methodological Limitations</h2>
    <ul>{html_limitations}</ul>
</body>
</html>"""

    # Persist files
    md_path = settings.REPORTS_DIR / f"{report_id}.md.enc"
    html_path = settings.REPORTS_DIR / f"{report_id}.html.enc"
    cipher = encryption_service()
    md_path.write_bytes(cipher.encrypt_bytes(markdown_content.encode("utf-8")))
    html_path.write_bytes(cipher.encrypt_bytes(html_content.encode("utf-8")))

    return {
        "report_id": report_id,
        "title": params.title,
        "markdown_content": markdown_content,
        "markdown_path": str(md_path),
        "html_path": str(html_path),
        "relative_markdown_url": f"/api/tasks/{quote(params.task_id, safe='')}/artifacts/markdown" if params.task_id else None,
        "relative_html_url": f"/api/tasks/{quote(params.task_id, safe='')}/artifacts/html" if params.task_id else None,
        "artifacts": [str(md_path), str(html_path)]
    }

